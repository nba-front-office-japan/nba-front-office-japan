/** 英語名の照合用(アクセント記号を外し、小文字にする。例: Luka Dončić → luka doncic) */
function normalizeName(name: string): string {
  return name.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();
}

const FEATURED_BY_NAME = new Map(FEATURED_PLAYERS.map((p) => [normalizeName(p.name), p]));

/** DBの英語名から有名選手の解説を探す。対象外の選手は null */
export function featuredPlayerFor(fullName: string): FeaturedPlayer | null {
  return FEATURED_BY_NAME.get(normalizeName(fullName)) ?? null;
}

/** 英語名が同じかどうか(アクセント記号・大文字小文字を区別しない) */
export function samePlayerName(a: string, b: string): boolean {
  return normalizeName(a) === normalizeName(b);
}
